const assert=require('node:assert/strict'),weekly=require('./weekly-team.js');
assert.equal(weekly.sunday(new Date('2026-10-16T12:00:00Z')),'2026-10-11');
assert.equal(weekly.sunday(new Date('2026-10-17T22:30:00Z')),'2026-10-18');
assert.equal(weekly.sunday(new Date('2026-10-25T01:30:00Z')),'2026-10-25');
const row=(id,pos,extra={})=>({source_team_id:1,source_player_id:id,position:pos,games:3,team_games:6,goals:1,assists:2,dim_complete:true,defensive_actions:12,goalie_complete:true,saves:30,goals_allowed:3,...extra});
const candidates=[row(1,'LW'),row(2,'LW',{goals:99,games:1}),row(3,'C'),row(4,'RW'),row(5,'LD'),row(6,'RD'),row(7,'G'),row(8,'G',{saves:90,goals_allowed:30}),row(9,'LD',{dim_complete:false,defensive_actions:100})];
const available=new Set(candidates.map(p=>p.source_team_id+':'+p.source_player_id)),picks=weekly.select(candidates,available);
assert.equal(Object.keys(picks).length,6);
assert.equal(picks.LW.source_player_id,1);
assert.equal(picks.LD.source_player_id,5);
assert.equal(picks.G.source_player_id,7);
assert.equal(weekly.select([],available).G,undefined);
assert.equal(weekly.select([row(1,'G',{saves:0,goals_allowed:0})],available).G,undefined);
assert.equal(weekly.select([row(1,'C')],new Set()).C,undefined);
console.log('Weekly team passed: Stockholm dates, Sunday rollover, DST, 50% boundary, points/DIM/SV ranking and missing data.');
const mixed=[row(20,'LW',{games:2,goals:2,assists:1,team_games:12}),row(20,'RW',{games:1,goals:7,assists:0,team_games:12}),row(20,'LD',{games:1,goals:99,assists:0,team_games:12}),row(21,'LD',{games:2,team_games:6,defensive_actions:10}),row(21,'RD',{games:1,team_games:6,defensive_actions:8})];
const combined=weekly.select(mixed,new Set(['1:20','1:21']));
assert.equal(combined.LW.goals,9);
assert.equal(combined.LW.games,3);
assert.equal(combined.RW,undefined);
assert.equal(combined.LD.games,3);
assert.equal(combined.LD.defensive_actions,18);
assert.equal(combined.LW.position,'LW');
assert.equal(weekly.select([row(22,'LD',{games:2,team_games:8})],new Set(['1:22'])).LD,undefined);
console.log('Role grouping passed: forward points combined, defense DIM combined, main positions and role isolation.');
const averages=[row(30,'LW',{games:8,team_games:8,goals:10,assists:10}),row(31,'LW',{games:4,team_games:8,goals:7,assists:7}),row(32,'LW',{games:2,team_games:8,goals:20,assists:0})];
const averageAvailable=new Set(['1:30','1:31','1:32']);
assert.equal(weekly.select(averages,averageAvailable,'total').LW.source_player_id,30);
assert.equal(weekly.select(averages,averageAvailable,'average').LW.source_player_id,31);
assert.equal(weekly.select([row(33,'C',{games:1,team_games:2,goals:10})],new Set(['1:33']),'average').C,undefined);
assert.equal(weekly.select(mixed,new Set(['1:20','1:21']),'average').LW,undefined);
assert.equal(weekly.select(mixed,new Set(['1:20','1:21']),'average').LD.source_player_id,21);
console.log('Forward metric passed: total vs average, exactly 50%, minimum 2 games and unchanged defender rules.');
