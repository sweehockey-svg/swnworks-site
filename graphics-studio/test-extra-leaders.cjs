const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/app.js','utf8');
const ctx=vm.createContext({S:{stage:'regular',count:8,teams:[],players:[]},n:v=>v!=null&&Number.isFinite(Number(v))?Number(v):0});
vm.runInContext(source.slice(source.indexOf('function ps('),source.indexOf('function dimPlayers(')),ctx);
const player=(id,gp,points,extra={})=>({sports_gamer_player_id:id,sports_gamer_team_id:1,display_gamertag:id,regular_skater_games:gp,regular_points:points,regular_goals:1,regular_assists:points-1,regular_skater_position_abbreviation:'LD',...extra});
ctx.S.teams=[{sports_gamer_team_id:1,statistics_stage:'regular',games_played:6},{sports_gamer_team_id:1,statistics_stage:'playoffs',games_played:2}];
ctx.S.players=[player('one-game',1,10),player('boundary',3,9),player('forward',6,12,{regular_skater_position_abbreviation:'C'}),player('missing',4,null)];
assert.equal(ctx.extraLeaders('points_average')[0].display_gamertag,'boundary');
assert.equal(ctx.extraLeaders('points_average').length,2);
assert.equal(ctx.extraLeaders('points_average',true).length,1);
ctx.S.stage='playoffs';
ctx.S.players=[player('playoff',0,0,{playoff_skater_games:1,playoff_points:4,playoff_skater_position_abbreviation:'RD'})];
assert.equal(ctx.extraLeaders('points_average',true)[0].score,4);
ctx.S.stage='total';
assert.equal(ctx.extraLeaders('points_average').length,0);
ctx.S.players=[player('weighted',3,9,{playoff_skater_games:1,playoff_points:1})];
assert.equal(ctx.extraLeaders('points_average')[0].score,2.5);
ctx.S.stage='regular';
ctx.S.players=[player('none',2,3),player('zero',2,3,{regular_hits:0,regular_penalty_minutes:0}),player('high',2,3,{regular_hits:14,regular_penalty_minutes:10}),player('low',2,3,{regular_hits:8,regular_penalty_minutes:4})];
assert.equal(ctx.extraLeaders('hits')[0].score,14);
assert.equal(ctx.extraLeaders('penalties')[0].score,10);
assert.equal(ctx.extraLeaders('hits').length,2);
assert.equal(ctx.extraLeaders('penalties').length,2);
console.log('Extra leader tests passed: qualification, position, periods, weighted average, nulls and totals.');
vm.runInContext(source.slice(source.indexOf('function gv('),source.indexOf('function stageName(')),ctx);
ctx.S.teams=[{sports_gamer_team_id:1,statistics_stage:'regular',games_played:5},{sports_gamer_team_id:1,statistics_stage:'playoffs',games_played:3}];
const goalie=(id,regular,playoffs,sv)=>({sports_gamer_team_id:1,display_gamertag:id,regular_goalie_games:regular,playoff_goalie_games:playoffs,regular_goalie_save_percentage:sv,playoff_goalie_save_percentage:sv});
ctx.S.players=[goalie('below',2,1,.99),goalie('qualified',3,2,.90),goalie('missing-save',4,2,null)];
ctx.S.stage='regular';
assert.equal(ctx.goalies().length,1);
assert.equal(ctx.goalies()[0].display_gamertag,'qualified');
ctx.S.stage='playoffs';
assert.equal(ctx.goalies().length,1);
ctx.S.stage='total';
assert.equal(ctx.goalies().length,1);
assert.equal(ctx.goalies()[0].teamGames,8);
ctx.S.teams=[{sports_gamer_team_id:1,statistics_stage:'regular',games_played:6}];
ctx.S.stage='regular';
assert.equal(ctx.goalies()[0].gp,3); // Exactly 50% qualifies.
ctx.S.teams=[];
assert.equal(ctx.goalies().length,0);
console.log('Goalie qualification passed: odd totals, exactly 50%, playoffs, combined periods and missing data.');
