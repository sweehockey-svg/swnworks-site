const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm');
const source=fs.readFileSync(__dirname+'/app.js','utf8');
const ctx={S:{stage:'regular'},L:{locale:'en-GB',t:x=>x},n:v=>Number(v)||0,rosterPosition:p=>p.position};
vm.createContext(ctx);
vm.runInContext(source.slice(source.indexOf('function ps('),source.indexOf('function qualificationPercent(')),ctx);
vm.runInContext(source.slice(source.indexOf('function gv('),source.indexOf('function goalies(')),ctx);
vm.runInContext(source.slice(source.indexOf('function rosterStatsValues('),source.indexOf('function rosterStatsSvg(')),ctx);
const player={position:'RW',regular_skater_games:6,regular_goals:3,regular_assists:5,regular_points:8,playoff_skater_games:2,playoff_goals:1,playoff_assists:2,playoff_points:3};
const values=p=>JSON.parse(JSON.stringify(ctx.rosterStatsValues(p)));
assert.deepEqual(values(player),[['GP','6'],['G','3'],['A','5'],['P','8']]);
ctx.S.stage='playoffs';assert.deepEqual(values(player),[['GP','2'],['G','1'],['A','2'],['P','3']]);
ctx.S.stage='total';assert.deepEqual(values(player),[['GP','8'],['G','4'],['A','7'],['P','11']]);
ctx.S.stage='regular';
assert.equal(values({position:'G',regular_goalie_games:6,regular_goalie_save_percentage:.8217})[1][1],'82.2');
assert.deepEqual(values({position:'G',regular_goalie_games:4,regular_goalie_save_percentage:80.5,regular_goalie_goals_against_average:2.25,regular_goalie_shutouts:1}),[['GP','4'],['SV%','80.5'],['GAA','2.25'],['SO','1']]);
assert.deepEqual(values({position:'G',regular_goalie_games:0}),[['GP','0'],['SV%','–'],['GAA','–'],['SO','–']]);
assert.deepEqual(values({position:'G',regular_goalie_games:1}),[['GP','1'],['SV%','–'],['GAA','–'],['SO','–']]);
assert(source.includes('S.rosterStats?rosterStatsSvg('));
ctx.measurePortrait=()=>{};ctx.esc=x=>x;ctx.portraitBounds=new Map();
vm.runInContext(source.slice(source.indexOf('function rosterPortrait('),source.indexOf('function rosterStatsValues(')),ctx);
const templateCrops=[];
for(const headWidth of [200,350,450]){
 ctx.portraitBounds.set('template',{left:headWidth/2,top:headWidth/10,width:900,height:1500,headWidth,sourceW:1024,sourceH:1536});
 templateCrops.push(ctx.rosterPortrait('template',0,0,160,240,18).match(/viewBox="([^"]+)"/)[1]);
}
assert.deepEqual(templateCrops,['256 0 512 768','256 0 512 768','256 0 512 768'],'Template portraits must share the same chest crop');
ctx.S.format='wide';
const singleRowCrop=ctx.rosterPortrait('template',0,0,150,560,9).match(/viewBox="([^"]+)"/)[1].split(' ').map(Number);
assert(singleRowCrop[2]>=1024*.35,'Single-row portraits need enough width for the head and shoulders');
ctx.S.format='portrait';

vm.runInContext(source.slice(source.indexOf('function rosterPosition('),source.indexOf('function selectedRoster(')),ctx);
ctx.S.stage='regular';
const goalieOnly={roster_preferred_position_abbreviation:'RD',regular_goalie_games:4,regular_skater_games:0,regular_goalie_save_percentage:.85};
assert.equal(ctx.rosterPosition(goalieOnly),'G');
assert.equal(values(goalieOnly)[1][0],'SV%');
assert.equal(ctx.rosterPosition({...goalieOnly,regular_skater_games:1}),'RD');
assert.equal(ctx.rosterPosition({...goalieOnly,playoff_skater_games:1}),'RD');
assert.equal(ctx.rosterPosition({...goalieOnly,regular_goalie_games:0}),'RD');
const skaterOnly={roster_preferred_position_abbreviation:'G',regular_goalie_games:0,regular_skater_games:3,regular_skater_position_abbreviation:'CE',regular_goals:2};
assert.equal(ctx.rosterPosition(skaterOnly),'C');
assert.equal(values(skaterOnly)[1][0],'G');
assert.equal(ctx.rosterPosition({...skaterOnly,regular_goalie_games:1}),'G');
assert.equal(ctx.rosterPosition({...skaterOnly,regular_skater_position_abbreviation:null,playoff_skater_position_abbreviation:'RW'}),'RW');
console.log('Roster stats and portrait crops passed, including goalie-only and mixed-role players.');
