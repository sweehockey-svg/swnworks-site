// SWN_PGLITE_TEST_MODULE can point to an isolated local @electric-sql/pglite install.
const fs=require('node:fs'),assert=require('node:assert/strict');
const {PGlite}=require(process.env.SWN_PGLITE_TEST_MODULE||'@electric-sql/pglite');
const read=name=>fs.readFileSync(__dirname+'/'+name,'utf8');
(async()=>{
 const db=new PGlite();
 try{
  await db.exec(`create role anon; create role authenticated; create role service_role; create schema auth; create schema broadcast_control;
   grant usage on schema broadcast_control to authenticated;
   create function auth.uid() returns uuid language sql as $$ select '00000000-0000-0000-0000-000000000001'::uuid $$;
   create function public.swn_studio_scene_access(text) returns boolean language sql as $$ select $1='broadcast-en' $$;
   create table public.broadcast_studio_state(channel text primary key,state jsonb,updated_at timestamptz);`);
  const scene=read('broadcast_scene_control.sql').split('create or replace function broadcast_control.set_scene')[1].split('create or replace function public.broadcast_studio_set_scene')[0];
  const music=read('broadcast_music_control.sql').split('create or replace function public.broadcast_studio_set_music')[0];
  await db.exec('create or replace function broadcast_control.set_scene'+scene+music+read('broadcast_team_order.sql'));
  const state={scene:'opening',lineupSide:'away',home:'1',away:'2',hs:'4',as:'2',videoSource:'twitch',twitchChannel:'fixture',twitchTeamChannels:{1:'fixture',2:'fixture_away'},transientSource:{ticket:'test-ticket',expires_at:new Date(Date.now()+3600000).toISOString()}};
  await db.query("insert into public.broadcast_studio_state values ('broadcast-en',$1,now()),('broadcast-fi',$1,now())",[state]);
  await db.exec('set role authenticated');
  await assert.rejects(db.query("select broadcast_control.set_scene('broadcast-fi','duallineup',null)"),{code:'42501'});
  const selected=(await db.query("select broadcast_control.set_scene('broadcast-en','duallineup',null) as result")).rows[0].result;
  assert.deepEqual(selected,{...state,scene:'duallineup'});
  const mixed=(await db.query("select broadcast_control.set_music('broadcast-en','duallineup','low') as result")).rows[0].result;
  assert.deepEqual(mixed,{...selected,sceneMusic:{muted:false,duallineup:'low'}});
  const expected=s=>({leagueId:s.leagueId??null,home:s.home,away:s.away,matchName:s.matchName??null,
   ticket:s.transientSource.ticket,teamOrderRevision:s.teamOrderRevision??null,liveTeamsReversed:s.liveTeamsReversed===true});
  const feedExpected=s=>({...expected(s),twitchChannel:s.twitchChannel,twitchTeamChannels:s.twitchTeamChannels});
  const control=(channel,guard,action)=>db.query('select public.broadcast_studio_set_team_order($1,$2,$3) as result',[channel,guard,action]);
  await assert.rejects(control('broadcast-fi',feedExpected(state),'stream-away'),{code:'42501'});
  await assert.rejects(control('broadcast-en',{...feedExpected(mixed),twitchTeamChannels:{1:'fixture',2:'injected'}},'stream-away'),{code:'P0002'});
  const away=(await control('broadcast-en',feedExpected(mixed),'stream-away')).rows[0].result;
  assert.deepEqual(away,{...mixed,twitchChannel:'fixture_away',liveTeamsReversed:true});
  await assert.rejects(control('broadcast-en',feedExpected(mixed),'stream-home'),{code:'P0002'});
  const swap=(await control('broadcast-en',expected(away),'swap')).rows[0].result;
  assert.equal(swap.home,'2');
  assert.equal(swap.twitchChannel,'fixture_away');
  assert.deepEqual(swap.twitchTeamChannels,state.twitchTeamChannels);
  const other=(await control('broadcast-en',feedExpected(swap),'stream-away')).rows[0].result;
  assert.deepEqual(other,{...swap,twitchChannel:'fixture',liveTeamsReversed:true});
  await assert.rejects(control('broadcast-fi',{...expected(state),overlayVisible:true},'team-strip'),{code:'42501'});
  const stripOff=(await control('broadcast-en',{...expected(other),overlayVisible:true},'team-strip')).rows[0].result;
  assert.deepEqual(stripOff,{...other,liveTeamStripShow:false});
  await assert.rejects(control('broadcast-en',{...expected(other),overlayVisible:true},'team-strip'),{code:'P0002'});
  const commentatorsOn=(await control('broadcast-en',{...expected(stripOff),overlayVisible:false},'commentators')).rows[0].result;
  assert.deepEqual(commentatorsOn,{...stripOff,liveCommentatorsShow:true});
  const stripOn=(await control('broadcast-en',{...expected(commentatorsOn),overlayVisible:false},'team-strip')).rows[0].result;
  assert.deepEqual(stripOn,{...commentatorsOn,liveTeamStripShow:true});
  const pick={...expected(stripOn),playerId:'345',playerTeam:stripOn.home};
  await assert.rejects(control('broadcast-fi',pick,'present-player'),{code:'42501'});
  await assert.rejects(control('broadcast-en',{...pick,playerTeam:'99'},'present-player'),{code:'22023'});
  await assert.rejects(control('broadcast-en',{...pick,playerId:'invalid'},'present-player'),{code:'22023'});
  await assert.rejects(control('broadcast-en',{...pick,ticket:'stale'},'present-player'),{code:'P0002'});
  const manual=(await control('broadcast-en',pick,'present-player')).rows[0].result;
  assert.deepEqual(manual,{...stripOn,scene:'spotlight',presentedPlayer:{id:'345',team:stripOn.home}});
  const automatic=(await db.query("select broadcast_control.set_scene('broadcast-en','spotlight',null) as result")).rows[0].result;
  assert.deepEqual(automatic,{...stripOn,scene:'spotlight'});
  for(const family of ['tourpoints','tourgoalies','tourstats']){
   for(const phase of ['','regular','playoff']){
    const scene=family+phase;
    await assert.rejects(db.query("select broadcast_control.set_scene('broadcast-fi',$1,null)",[scene]),{code:'42501'});
    const tournament=(await db.query("select broadcast_control.set_scene('broadcast-en',$1,null) as result",[scene])).rows[0].result;
    assert.equal(tournament.scene,scene);
    assert.equal(tournament.hs,automatic.hs);
    const withMusic=(await db.query("select broadcast_control.set_music('broadcast-en',$1,'low') as result",[scene])).rows[0].result;
    assert.equal(withMusic.sceneMusic[scene],'low');
   }
  }
  const baseLineups={home:{LW:'201',C:'202',RW:'',LD:'',RD:'',G:''},away:{LW:'301',C:'',RW:'',LD:'',RD:'',G:''}};
  const reorder={...expected(automatic),baseLineups,lineups:{...baseLineups,home:{...baseLineups.home,LW:'202',C:'',RW:'201'}}};
  await assert.rejects(control('broadcast-fi',reorder,'reorder-lineups'),{code:'42501'});
  await assert.rejects(control('broadcast-en',reorder,'reorder-lineups'),{code:'P0002'});
  await db.exec('reset role');
  const formation={...automatic,scene:'duallineup',lineups:baseLineups};
  await db.query("update public.broadcast_studio_state set state=$1 where channel='broadcast-en'",[formation]);
  await db.exec('set role authenticated');
  const foreign={...reorder.lineups,home:{...reorder.lineups.home,LW:'301'},away:{...reorder.lineups.away,LW:'202'}};
  await assert.rejects(control('broadcast-en',{...reorder,lineups:foreign},'reorder-lineups'),{code:'22023'});
  const unknown={...reorder.lineups,home:{...reorder.lineups.home,EXTRA:'201'}};
  await assert.rejects(control('broadcast-en',{...reorder,lineups:unknown},'reorder-lineups'),{code:'22023'});
  await assert.rejects(control('broadcast-en',{...reorder,ticket:'stale'},'reorder-lineups'),{code:'P0002'});
  const reordered=(await control('broadcast-en',reorder,'reorder-lineups')).rows[0].result;
  assert.deepEqual(reordered,{...formation,lineups:reorder.lineups});
  await assert.rejects(control('broadcast-en',reorder,'reorder-lineups'),{code:'P0002'});
  await db.exec('reset role');
  await db.exec(read('broadcast_verified_lineups.sql'));
  const verified={...reordered,leagueId:527};
  await db.query("update public.broadcast_studio_state set state=$1 where channel='broadcast-en'",[verified]);
  const verifiedGuard={...expected(verified),baseLineups:verified.lineups};
  const incoming={...verified.lineups,home:{...verified.lineups.home,RW:'999'}};
  const replace=()=>db.query("select public.broadcast_studio_set_verified_lineups('broadcast-en',$1,$2) as result",[verifiedGuard,incoming]);
  await db.exec('set role authenticated');
  await assert.rejects(replace(),{code:'42501'});
  await db.exec('set role service_role');
  assert.deepEqual((await replace()).rows[0].result,{...verified,lineups:incoming});
  await assert.rejects(replace(),{code:'P0002'});
  await db.exec('reset role');
  assert.equal((await db.query("select has_function_privilege('anon','broadcast_control.set_scene(text,text,text)','EXECUTE') as allowed")).rows[0].allowed,false);
  assert.equal((await db.query("select has_function_privilege('anon','public.broadcast_studio_set_team_order(text,jsonb,text)','EXECUTE') as allowed")).rows[0].allowed,false);
  console.log('PASS authorized scene, music and team feeds; stale and unauthorized switches rejected. Local Postgres only.');
 }finally{await db.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
