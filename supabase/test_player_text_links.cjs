const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const source=fs.readFileSync(require('node:path').join(__dirname,'../commentator-cockpit/hockeyettan/cockpit.js'),'utf8');
const context={state:{searchRoster:[],seasonPlayerStats:[],seasonGoalieStats:[],recentPlayerStats:[],recentGoalieStats:[],currentPlayerStats:[],currentGoalieStats:[]},humanSourceName:s=>s,cleanLineupSourceName:s=>s,nationalityMarkup:()=>'',esc:s=>String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;').replace(/"/g,'&quot;')};
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('  function playerTextMarkup('),source.indexOf("  const playerCardDialog=")),context);
const render=context.playerTextMarkup;
const goal=render('#14 Theo Hårdstam (2) · Ass: #46 Jesper Valente, #33 Gustav Meijer','home');
assert.equal((goal.match(/data-player-card=/g)||[]).length,3);
assert.ok(goal.includes('Theo Hårdstam</button> (2)'));
assert.ok(goal.includes('Gustav Meijer</button>'));
assert.ok(render('#16 Johannes Mäki · High Sticking (58:32 - 60:00)','away').includes('Johannes Mäki</button> · High Sticking'));
assert.ok(render('#31 Artur Ogandzhanian','away').includes('Artur Ogandzhanian</button>'));
context.state.searchRoster=[{player_id:'a',team_id:'home',source_name:'Jesper Valente'}];
assert.ok(render('Jesper Valente · 3 mål').includes('data-player-card='));
assert.ok(!render('Jesper Valenteberg').includes('data-player-card='));
context.state.searchRoster.push({player_id:'b',team_id:'away',source_name:'Jesper Valente'});
assert.ok(!render('Jesper Valente').includes('data-player-card='));
assert.ok(render('<img src=x onerror=alert(1)>').includes('&lt;img'));
console.log('Player links: goal, assists, penalty, goalie, identity ambiguity and HTML escaping passed.');
